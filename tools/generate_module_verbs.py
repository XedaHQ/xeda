def _double_quoted(text: str) -> str:
    """Return `text` with double quotes for its string literals, as black writes them."""
    return text.replace("'", '"') if '"' not in text else text


def _text(annotation: Any) -> str:
    """Return the source text of an annotation (a string, as the modules postpone them)."""
    if not isinstance(annotation, str):
        raise TypeError(f"annotation {annotation!r} is not postponed text")
    tree = ast.parse(annotation, mode="eval").body
    if isinstance(tree, ast.Constant) and isinstance(tree.value, str):
        return tree.value  # a quoted forward reference
    return _double_quoted(annotation)


def _parameter(parameter: inspect.Parameter) -> str:
    text = parameter.name
    if parameter.annotation is not inspect.Parameter.empty:
        text += f": {_text(parameter.annotation)}"
    if parameter.default is not inspect.Parameter.empty:
        text += f" = {_double_quoted(repr(parameter.default))}"
    return text


def _paragraph(options: tuple[str, ...], refuse_plan: str | None) -> str:
    if options:
        names = ", ".join(f"`{name}`" for name in options)
        text = (
            f"The keyword-only parameters {names} configure the `Workspace` that this call "
            "makes. They have the same meaning and defaults as the parameters of `Workspace`."
        )
    else:
        text = "This function needs no workspace and none of its options."
    if refuse_plan:
        text += (
            " Unlike `Workspace.run`, this function takes a `Spec` only, and each launch option "
            "has the default of `Workspace.plan`. It raises `TypeError` for a `Plan`. Run a plan "
            "with the workspace that made it: `ws.run(plan)`."
        )
    return "\n".join(textwrap.wrap(text, width=92))


def verb_source(
    method: Callable[..., Any],
    *,
    workspace_options: tuple[str, ...],
    options_first: bool,
    overrides: Mapping[str, str] = {},
    refuse_plan: str | None = None,
) -> str:
    """Return the source text of the module-level verb of `method`.

    The workspace options take the defaults and annotations of the `Workspace` constructor, and
    stand after the positional parameters (`options_first`) or after the keyword-only parameters
    of the method. `overrides` replaces the text of a parameter by the name in the method; the
    name before the first colon is the name in the verb. `refuse_plan` names a parameter that
    raises `TypeError` for a `Plan`."""
    constructor = inspect.signature(Workspace).parameters
    # (verb name, source text, kind) of the parameters of the method.
    own = [
        (
            (
                overrides[p.name].split(":")[0].split("=")[0].strip()
                if p.name in overrides
                else p.name
            ),
            overrides.get(p.name) or _parameter(p),
            p.kind,
        )
        for p in inspect.signature(method).parameters.values()
        if p.name != "self"
    ]
    options = [(name, _parameter(constructor[name])) for name in workspace_options]
    positional = [(n, t) for n, t, k in own if k is inspect.Parameter.POSITIONAL_ONLY]
    keyword = [(n, t) for n, t, k in own if k is inspect.Parameter.KEYWORD_ONLY]
    if len(positional) + len(keyword) != len(own):
        raise ValueError(f"{method.__qualname__} has a parameter of a kind this tool does not use")
    keyword = [*options, *keyword] if options_first else [*keyword, *options]
    lines = [f"    {text}," for _, text in positional]
    if positional:
        lines.append("    /,")
    if keyword:
        lines.append("    *,")
        lines += [f"    {text}," for _, text in keyword]
    returns = _text(inspect.signature(method).return_annotation)
    name = method.__name__
    own_keywords = [n for n, _ in keyword if n not in workspace_options]
    doc = inspect.getdoc(method) or ""
    doc = f"{doc}\n\n{_paragraph(workspace_options, refuse_plan)}"
    if '"""' in doc or "\\" in doc:
        raise ValueError(f"the docstring of {method.__qualname__} needs escapes")
    body = textwrap.indent(f'"""{doc}"""', "    ")
    guard = ""
    if refuse_plan:
        guard = (
            f"    if isinstance({refuse_plan}, Plan):\n"
            "        raise TypeError(\n"
            f'            "`{name}` takes a `Spec`. To run a `Plan`, use the workspace that made it: "\n'
            '            "`ws.run(plan)`."\n'
            "        )\n"
        )
    source = f"def {name}(\n" + "\n".join(lines) + f"\n) -> {returns}:\n{body}\n{guard}"
    source += _return(workspace_options, name, positional, own_keywords)
    return source


def _return(
    options: tuple[str, ...],
    name: str,
    positional: list[tuple[str, str]],
    keywords: list[str],
) -> str:
    def call(arguments: list[str]) -> str:
        if not arguments:
            return "()"
        return "(\n" + "".join(f"        {a},\n" for a in arguments) + "    )"

    if name == "load":
        return "    return Workspace.load(run_dir)\n"
    made = call([f"{option}={option}" for option in options])
    given = call([*(n for n, _ in positional), *(f"{k}={k}" for k in keywords)])
    return f"    return Workspace{made}.{name}{given}\n"


def render() -> str:
    parts = [HEADER]
    for name, (options, first, overrides, refuse) in VERBS.items():
        parts.append(
            verb_source(
                getattr(Workspace, name),
                workspace_options=options,
                options_first=first,
                overrides=overrides,
                refuse_plan=refuse,
            )
        )
    return "\n\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in file is stale")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != generated:
            print(
                f"{TARGET.relative_to(ROOT)} is stale; run python tools/generate_module_verbs.py",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
